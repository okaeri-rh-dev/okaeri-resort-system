/**
 * Custom Service Worker for Okaeri Resort System
 * Implements advanced caching strategies, offline sync, and background operations
 * Optimized for resort management operations with poor connectivity
 */

import { precacheAndRoute, cleanupOutdatedCaches } from "workbox-precaching";
import { registerRoute, NavigationRoute } from "workbox-routing";
import { NetworkFirst, CacheFirst, StaleWhileRevalidate, NetworkOnly } from "workbox-strategies";
import { BackgroundSync } from "workbox-background-sync";
import { ExpirationPlugin } from "workbox-expiration";
import { CacheableResponsePlugin } from "workbox-cacheable-response";

declare const self: ServiceWorkerGlobalScope;

// Precache all static assets generated by Vite
precacheAndRoute(self.__WB_MANIFEST);

// Clean up old caches
cleanupOutdatedCaches();

/**
 * Advanced caching strategies for different resource types
 */

// 1. API Routes - Network-first with fast fallback
registerRoute(
  ({ request }) => request.url.includes("/api/") && request.method === "GET",
  new NetworkFirst({
    cacheName: "api-cache",
    networkTimeoutSeconds: 3, // Fast timeout for poor connectivity
    plugins: [
      new CacheableResponsePlugin({
        statuses: [0, 200, 206],
      }),
      new ExpirationPlugin({
        maxEntries: 200,
        maxAgeSeconds: 5 * 60, // 5 minutes
        purgeOnQuotaError: true,
      }),
    ],
  })
);

// 2. Dashboard data - Stale-while-revalidate for real-time feel
registerRoute(
  ({ request, url }) =>
    url.pathname.includes("/dashboard") ||
    url.pathname.includes("/stats") ||
    url.pathname.includes("/recent"),
  new StaleWhileRevalidate({
    cacheName: "dashboard-cache",
    plugins: [
      new CacheableResponsePlugin({
        statuses: [0, 200],
      }),
      new ExpirationPlugin({
        maxEntries: 50,
        maxAgeSeconds: 10 * 60, // 10 minutes
        purgeOnQuotaError: true,
      }),
    ],
  })
);

// 3. Static assets - Cache-first with long expiration
registerRoute(
  ({ request }) =>
    request.destination === "style" ||
    request.destination === "script" ||
    request.destination === "font",
  new CacheFirst({
    cacheName: "static-assets",
    plugins: [
      new CacheableResponsePlugin({
        statuses: [0, 200],
      }),
      new ExpirationPlugin({
        maxEntries: 100,
        maxAgeSeconds: 7 * 24 * 60 * 60, // 7 days
        purgeOnQuotaError: true,
      }),
    ],
  })
);

// 4. Images - Cache-first with smart compression
registerRoute(
  ({ request }) => request.destination === "image",
  new CacheFirst({
    cacheName: "images-cache",
    plugins: [
      new CacheableResponsePlugin({
        statuses: [0, 200],
      }),
      new ExpirationPlugin({
        maxEntries: 300,
        maxAgeSeconds: 30 * 24 * 60 * 60, // 30 days
        purgeOnQuotaError: true,
      }),
    ],
  })
);

// 5. Document routes - Network-first with offline fallback
const navigationRoute = new NavigationRoute(
  new NetworkFirst({
    cacheName: "pages-cache",
    networkTimeoutSeconds: 3,
    plugins: [
      new CacheableResponsePlugin({
        statuses: [0, 200],
      }),
      new ExpirationPlugin({
        maxEntries: 50,
        maxAgeSeconds: 24 * 60 * 60, // 24 hours
        purgeOnQuotaError: true,
      }),
    ],
  }),
  {
    // Allow all origins for navigation requests
    allowlist: [/^\/(?!__)/],
    // Deny admin routes for offline access
    denylist: [/\/__admin/, /\/api\/admin/],
  }
);

registerRoute(navigationRoute);

/**
 * Background Sync for Critical Operations
 */

// Background sync for form submissions
const bgSync = new BackgroundSync("form-submissions", {
  maxRetentionTime: 24 * 60, // 24 hours
  onSync: async ({ queue }) => {
    let entry;
    while ((entry = await queue.shiftRequest())) {
      try {
        await fetch(entry.request);
        console.log("Background sync successful:", entry.request.url);
      } catch (error) {
        console.error("Background sync failed:", error);
        // Re-add to queue for retry
        await queue.unshiftRequest(entry);
        throw error;
      }
    }
  },
});

// Register background sync routes
registerRoute(
  ({ request, url }) => {
    const isMutation = request.method !== "GET";
    const isImportantRoute =
      url.pathname.includes("/bookings") ||
      url.pathname.includes("/expenses") ||
      url.pathname.includes("/payments");
    return isMutation && isImportantRoute;
  },
  new NetworkOnly({
    plugins: [bgSync],
  })
);

/**
 * Advanced Offline Functionality
 */

// Cache essential application shell
const ESSENTIAL_CACHE = "essential-v1";
const ESSENTIAL_URLS = ["/", "/dashboard", "/offline", "/manifest.json"];

// Install event - cache essential resources
self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(ESSENTIAL_CACHE)
      .then((cache) => cache.addAll(ESSENTIAL_URLS))
      .then(() => self.skipWaiting())
  );
});

// Activate event - clean up old caches
self.addEventListener("activate", (event) => {
  event.waitUntil(
    Promise.all([
      self.clients.claim(),
      caches.keys().then((cacheNames) => {
        return Promise.all(
          cacheNames
            .filter(
              (cacheName) => cacheName.startsWith("essential-") && cacheName !== ESSENTIAL_CACHE
            )
            .map((cacheName) => caches.delete(cacheName))
        );
      }),
    ])
  );
});

/**
 * Push Notifications for Critical Updates
 */
self.addEventListener("push", (event) => {
  if (!event.data) return;

  try {
    const data = event.data.json();
    const options: NotificationOptions = {
      body: data.body,
      icon: "/icons/icon-192x192.png",
      badge: "/icons/icon-96x96.png",
      image: data.image,
      actions: data.actions || [
        {
          action: "view",
          title: "View",
          icon: "/icons/action-view.png",
        },
        {
          action: "dismiss",
          title: "Dismiss",
          icon: "/icons/action-dismiss.png",
        },
      ],
      requireInteraction: data.urgent || false,
      tag: data.tag || "default",
      timestamp: Date.now(),
      data: data.data,
    };

    event.waitUntil(self.registration.showNotification(data.title, options));
  } catch (error) {
    console.error("Push notification error:", error);
  }
});

// Handle notification clicks
self.addEventListener("notificationclick", (event) => {
  event.notification.close();

  const { action } = event;
  const { data } = event.notification;

  if (action === "dismiss") {
    return;
  }

  // Handle view action or notification click
  event.waitUntil(
    self.clients.matchAll({ type: "window" }).then((clients) => {
      // Try to focus existing window
      for (const client of clients) {
        if (client.url.includes(data?.route || "/dashboard") && "focus" in client) {
          return client.focus();
        }
      }

      // Open new window
      return self.clients.openWindow(data?.route || "/dashboard");
    })
  );
});

/**
 * Intelligent Cache Management
 */

// Custom cache strategy based on connection type
self.addEventListener("fetch", (event) => {
  const { request } = event;
  const url = new URL(request.url);

  // Skip non-GET requests for background sync
  if (request.method !== "GET") {
    return;
  }

  // Skip cross-origin requests
  if (url.origin !== location.origin) {
    return;
  }

  // Handle offline page requests
  if (url.pathname === "/offline") {
    event.respondWith(
      caches.match(request).then((response) => {
        return response || fetch(request);
      })
    );
    return;
  }

  // Smart caching based on route importance
  const isEssential = ESSENTIAL_URLS.some((essentialUrl) => url.pathname.startsWith(essentialUrl));

  if (isEssential) {
    event.respondWith(
      caches.match(request).then((response) => {
        if (response) {
          // Update cache in background
          fetch(request)
            .then((fetchResponse) => {
              if (fetchResponse.ok) {
                caches.open(ESSENTIAL_CACHE).then((cache) => {
                  cache.put(request, fetchResponse.clone());
                });
              }
            })
            .catch(() => {
              // Silently fail background updates
            });
          return response;
        }

        return fetch(request)
          .then((fetchResponse) => {
            if (fetchResponse.ok) {
              caches.open(ESSENTIAL_CACHE).then((cache) => {
                cache.put(request, fetchResponse.clone());
              });
            }
            return fetchResponse;
          })
          .catch(() => {
            // Fallback to offline page for navigation requests
            if (request.mode === "navigate") {
              return (
                caches.match("/offline") ||
                new Response("Offline", { status: 503, statusText: "Service Unavailable" })
              );
            }
            throw new Error("Network error");
          });
      })
    );
  }
});

/**
 * Performance Monitoring
 */

// Track cache hit rates
let cacheHits = 0;
let totalRequests = 0;

self.addEventListener("fetch", (event) => {
  if (event.request.method === "GET") {
    totalRequests++;

    const originalResponse = event.respondWith;
    if (originalResponse) {
      event.respondWith = function (response) {
        if (response instanceof Promise) {
          response
            .then((res) => {
              if (res && res.headers && res.headers.get("X-Cache") === "HIT") {
                cacheHits++;
              }
            })
            .catch(() => {});
        }
        return originalResponse.call(this, response);
      };
    }
  }
});

// Report performance metrics periodically
setInterval(() => {
  if (totalRequests > 0) {
    const hitRate = (cacheHits / totalRequests) * 100;

    // Send to main thread
    self.clients.matchAll().then((clients) => {
      clients.forEach((client) => {
        client.postMessage({
          type: "SW_PERFORMANCE",
          data: {
            cacheHitRate: hitRate,
            totalRequests,
            cacheHits,
          },
        });
      });
    });

    // Reset counters
    cacheHits = 0;
    totalRequests = 0;
  }
}, 60000); // Every minute

/**
 * Connection-aware optimizations
 */
self.addEventListener("message", (event) => {
  const { data } = event;

  if (data.type === "CONNECTION_CHANGE") {
    const { effectiveType, downlink } = data.connection;

    // Adjust cache strategies based on connection
    if (effectiveType === "2g" || downlink < 0.5) {
      // Aggressive caching for slow connections
      console.log("Slow connection detected, enabling aggressive caching");
    } else if (effectiveType === "4g" && downlink > 2) {
      // More network requests for fast connections
      console.log("Fast connection detected, reducing cache dependency");
    }
  }

  if (data.type === "SKIP_WAITING") {
    self.skipWaiting();
  }
});

/**
 * Offline Queue Management
 */
interface OfflineAction {
  id: string;
  method: string;
  url: string;
  body?: any;
  headers?: Record<string, string>;
  timestamp: number;
  retryCount: number;
}

class OfflineQueue {
  private readonly storeName = "offline-actions";
  private readonly maxRetries = 3;

  async add(action: Omit<OfflineAction, "id" | "timestamp" | "retryCount">) {
    const db = await this.openDB();
    const transaction = db.transaction([this.storeName], "readwrite");
    const store = transaction.objectStore(this.storeName);

    const offlineAction: OfflineAction = {
      ...action,
      id: `${Date.now()}-${Math.random().toString(36).substr(2, 9)}`,
      timestamp: Date.now(),
      retryCount: 0,
    };

    await store.add(offlineAction);
  }

  async processQueue() {
    const db = await this.openDB();
    const transaction = db.transaction([this.storeName], "readwrite");
    const store = transaction.objectStore(this.storeName);
    const actions = await store.getAll();

    for (const action of actions) {
      try {
        const response = await fetch(action.url, {
          method: action.method,
          body: action.body ? JSON.stringify(action.body) : undefined,
          headers: {
            "Content-Type": "application/json",
            ...action.headers,
          },
        });

        if (response.ok) {
          // Success - remove from queue
          await store.delete(action.id);
        } else {
          // Failed - increment retry count
          action.retryCount++;
          if (action.retryCount >= this.maxRetries) {
            await store.delete(action.id);
          } else {
            await store.put(action);
          }
        }
      } catch (error) {
        // Network error - increment retry count
        action.retryCount++;
        if (action.retryCount >= this.maxRetries) {
          await store.delete(action.id);
        } else {
          await store.put(action);
        }
      }
    }
  }

  private async openDB(): Promise<IDBDatabase> {
    return new Promise((resolve, reject) => {
      const request = indexedDB.open("OkaeriOfflineDB", 1);

      request.onerror = () => reject(request.error);
      request.onsuccess = () => resolve(request.result);

      request.onupgradeneeded = () => {
        const db = request.result;
        if (!db.objectStoreNames.contains(this.storeName)) {
          db.createObjectStore(this.storeName, { keyPath: "id" });
        }
      };
    });
  }
}

const offlineQueue = new OfflineQueue();

// Process offline queue when online
self.addEventListener("online", () => {
  offlineQueue.processQueue().catch(console.error);
});

console.log("Okaeri Resort System Service Worker loaded successfully");
